function buildCategoryNavigation() {
    const categories = [...document.querySelectorAll('.menu-category')];
    if (!categories.length) return;

    const visualThemes = [
        'botanical', 'blossom', 'lattice', 'checker', 'lattice', 'botanical',
        'blossom', 'blossom', 'botanical', 'arches', 'arches', 'lattice',
        'botanical', 'citrus', 'blossom', 'citrus', 'arches', 'blossom',
        'botanical', 'blossom', 'lattice', 'blossom', 'checker', 'arches',
        'blossom', 'checker', 'lattice', 'citrus', 'citrus', 'citrus',
        'botanical', 'botanical'
    ];
    const signatureColors = [
        '#7d8767', '#b67c70', '#8c936b', '#bc7650', '#879071', '#be8066',
        '#b67c70', '#bd806e', '#8b9270', '#b88459', '#879071', '#898d73',
        '#7d8767', '#bb805c', '#b67c70', '#8b9270', '#85906d', '#b67c70',
        '#829071', '#b77b68', '#bc7650', '#b67c70', '#bc7650', '#879071',
        '#b67c70', '#bc7650', '#879071', '#c17d50', '#c17d50', '#c17d50',
        '#7d8767', '#879071'
    ];

    const nav = document.createElement('nav');
    nav.className = 'category-nav';
    nav.setAttribute('aria-label', 'Menu categories');
    nav.innerHTML = '<span class="nav-label">Explore the menu</span><div class="category-links"></div>';
    const links = nav.querySelector('.category-links');

    categories.forEach((section, index) => {
        const heading = section.querySelector('.category-title');
        if (!heading) return;
        section.id = `category-${index + 1}`;
        section.dataset.theme = visualThemes[index % visualThemes.length];
        section.style.setProperty('--section-accent', signatureColors[index % signatureColors.length]);
        section.style.setProperty('--motif-x', `${(index * 37) % 180}px`);
        section.style.setProperty('--motif-y', `${(index * 29) % 160}px`);
        const link = document.createElement('a');
        link.href = `#${section.id}`;
        link.textContent = heading.textContent.trim();
        links.append(link);
    });

    document.querySelector('.language-switcher')?.after(nav);
}

function changeLanguage(lang, buttonElement) {
    const selected = translations[lang] ? lang : 'fr';
    document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.toggle('active', btn === buttonElement));

    document.documentElement.lang = selected;
    document.documentElement.dir = selected === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('h2').forEach((heading, index) => {
        const key = headingKeys[index];
        if (key) heading.dataset.translate = key;
    });

    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.dataset.translate;
        const translated = translations[selected]?.[key];
        if (translated) element.textContent = translated;
    });

    document.querySelectorAll('.item-name, .item-desc').forEach(element => {
        if (!Object.prototype.hasOwnProperty.call(element.dataset, 'sourceText')) {
            element.dataset.sourceText = element.textContent.trim();
        }
        const sourceText = element.dataset.sourceText;
        element.textContent = selected === 'fr'
            ? sourceText
            : (catalogTranslations[sourceText]?.[selected] || sourceText);
    });

    document.querySelectorAll('.category-links a').forEach((link, index) => {
        const heading = document.querySelectorAll('.menu-category .category-title')[index];
        if (heading) link.textContent = heading.textContent.trim();
    });

    try { localStorage.setItem('selectedLang', selected); } catch { /* Storage can be disabled in private browsing. */ }
}

window.addEventListener('DOMContentLoaded', () => {
    buildCategoryNavigation();
    let savedLang = 'fr';
    try { savedLang = localStorage.getItem('selectedLang') || 'fr'; } catch { /* Keep French when storage is unavailable. */ }
    const targetButton = document.querySelector(`.lang-btn[onclick*="${savedLang}"]`);
    changeLanguage(savedLang, targetButton || document.querySelector('.lang-btn'));
});

window.addEventListener('scroll', () => {
    const button = document.getElementById('scrollTopBtn');
    if (button) button.style.display = window.scrollY > 200 ? 'flex' : 'none';
}, { passive: true });

